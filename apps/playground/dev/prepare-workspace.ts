/**
 * Creates the playground's editable copy of a fixture project.
 *
 * Edits never touch `examples/`: the fixture is copied into a git-ignored
 * workspace, its `src/app` JSX is instrumented with `data-oid`, and the
 * preview bridge is installed through Next.js `instrumentation-client.ts`
 * (a new file, so no fixture source is rewritten for the bridge).
 */
import {
  cp,
  mkdir,
  readdir,
  readFile,
  rm,
  stat,
  symlink,
  writeFile,
} from "node:fs/promises";
import { join } from "node:path";
import { instrumentSource } from "@allstudio/editor/source-mapper";

const COPIED_ENTRIES = [
  "src",
  "public",
  "next.config.ts",
  "tsconfig.json",
  "package.json",
];
const MARKER_FILE = ".allstudio-workspace.json";
const BRIDGE_FILE = "src/allstudio-preview-bridge.ts";
const INSTRUMENTATION_FILE = "src/instrumentation-client.ts";

export interface PrepareWorkspaceOptions {
  fixtureDir: string;
  workspaceDir: string;
  /** Source of `installPreviewBridge`, copied verbatim into the workspace. */
  bridgeSourceFile: string;
  editorOrigin: string;
  /** Delete an existing workspace first. Default keeps previous edits. */
  reset?: boolean;
}

export interface PreparedWorkspace {
  created: boolean;
  instrumentedFiles: string[];
}

async function exists(path: string): Promise<boolean> {
  return stat(path).then(
    () => true,
    () => false,
  );
}

export async function prepareWorkspace(
  options: PrepareWorkspaceOptions,
): Promise<PreparedWorkspace> {
  const { fixtureDir, workspaceDir } = options;
  if (options.reset) {
    await rm(workspaceDir, { recursive: true, force: true });
  }
  if (await exists(join(workspaceDir, MARKER_FILE))) {
    return { created: false, instrumentedFiles: [] };
  }
  await rm(workspaceDir, { recursive: true, force: true });
  await mkdir(workspaceDir, { recursive: true });

  for (const entry of COPIED_ENTRIES) {
    const from = join(fixtureDir, entry);
    if (await exists(from)) {
      await cp(from, join(workspaceDir, entry), {
        recursive: true,
        verbatimSymlinks: true,
      });
    }
  }
  // Reuse the fixture's installed dependencies; the adapter never follows symlinks.
  const fixtureModules = join(fixtureDir, "node_modules");
  if (await exists(fixtureModules)) {
    await symlink(fixtureModules, join(workspaceDir, "node_modules"), "dir");
  }

  const instrumentedFiles: string[] = [];
  const appDir = join(workspaceDir, "src", "app");
  for (const name of (await readdir(appDir)).sort()) {
    if (!name.endsWith(".tsx")) {
      continue;
    }
    const file = join(appDir, name);
    const result = instrumentSource(await readFile(file, "utf8"));
    if (!result.ok) {
      throw new Error(`Could not instrument ${file}: ${result.reason}`);
    }
    await writeFile(file, result.content, "utf8");
    instrumentedFiles.push(`src/app/${name}`);
  }

  await writeFile(
    join(workspaceDir, BRIDGE_FILE),
    await readFile(options.bridgeSourceFile, "utf8"),
    "utf8",
  );
  await writeFile(
    join(workspaceDir, INSTRUMENTATION_FILE),
    [
      "// Generated by the allstudio playground. Development workspace only.",
      'import { installPreviewBridge } from "./allstudio-preview-bridge";',
      "",
      `installPreviewBridge({ editorOrigin: ${JSON.stringify(options.editorOrigin)} });`,
      "",
    ].join("\n"),
    "utf8",
  );
  await writeFile(
    join(workspaceDir, MARKER_FILE),
    `${JSON.stringify({ fixture: fixtureDir, instrumentedFiles }, null, 2)}\n`,
    "utf8",
  );
  return { created: true, instrumentedFiles };
}
